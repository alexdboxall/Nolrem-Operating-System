#pragma once

#include "../../bitmap_generic/bmp.h"

typedef struct {
    int num_checkpoints;         // one per PAGE_SIZE-sized chunk of the plane data
    bmp_row_checkpoint_t* state; // [num_checkpoints], AllocHeap'd
} compat_bitmap_reload_t;

typedef struct {
    compat_bitmap_reload_t* reload; // NULL for non-RLE sources (or if it couldn't be allocated)
    uint8_t* planes;                // VMM file-backed region, lazily generated by BitmapReload
    uint8_t* src;                   // VMM file-backed mapping of the whole .bmp file
    size_t src_size;
    int width;                      // resolved target size
    int height;
    size_t total_len;               // bytes of plane data
} compat_bitmap_storage_t;
